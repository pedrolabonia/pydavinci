"""
Regenerates ``src/pydavinci/wrappers/_resolve_stubs.pyi`` from the official ``DaVinciResolveScript.pyi`` of
DaVinci Resolve (19.1 and later ship it in their Developer/Scripting folder, see ``DEFAULT_STUB``).

The official stub names the API classes like Resolve does (``Resolve``, ``MediaPoolItem``, ...). pydavinci uses those
names for its wrappers, so the generated stub renames every API class to ``PyRemote<Name>`` (``PyRemoteMediaPoolItem``)
- in class definitions, annotations and quoted forward references, but not in docstrings or method names. Deprecated
functions that pydavinci still calls (see ``DEPRECATED``) are added to their classes, so type checks keep working.

Usage::

    python tools/update_resolve_stubs.py [path/to/DaVinciResolveScript.pyi]

Writes the stub with CRLF line endings, like the rest of pydavinci.
"""
import ast
import io
import os
import sys
import tokenize
from pathlib import Path
from typing import Dict, List, Tuple

DEFAULT_STUB = Path(os.path.expandvars(
    r"%PROGRAMDATA%\Blackmagic Design\DaVinci Resolve\Support\Developer\Scripting\DaVinciResolveScript.pyi"
))
TARGET = Path(__file__).resolve().parents[1] / "src" / "pydavinci" / "wrappers" / "_resolve_stubs.pyi"

#: classes of the official stub that are no API objects
NOT_RENAMED = {"STYPE_BOOL", "STYPE_STR"}

#: deprecated functions still called by pydavinci (they work in Resolve 21.1.2), added to the renamed classes
DEPRECATED: Dict[str, List[str]] = {
    "PyRemoteProject": [
        "def GetSetting(self, settingName: str | None = None) -> Any: ...",
        "def SetSetting(self, settingName: str, settingValue: Any, *args: Any) -> bool: ...",
        "def GetPresetList(self) -> list[ProjectSettingsPresetInfo]: ...",
        "def SetPreset(self, presetName: str) -> bool: ...",
    ],
    "PyRemoteTimeline": [
        "def GetSetting(self, settingName: str | None = None) -> Any: ...",
        "def SetSetting(self, settingName: str, settingValue: Any) -> bool: ...",
    ],
    "PyRemoteTimelineItem": [
        "def GetProperty(self, propertyKey: str | None = None) -> Any: ...",
        "def SetProperty(self, propertyKey: str, propertyValue: Any) -> bool: ...",
        "def GetNumNodes(self) -> int: ...",
        "def SetLUT(self, nodeIndex: int, lutPath: str) -> bool: ...",
        "def GetLUT(self, nodeIndex: int) -> str: ...",
    ],
}

HEADER = '''# flake8: noqa
# Generated by tools/update_resolve_stubs.py from the official DaVinciResolveScript.pyi {version}
# (DaVinci Resolve Developer/Scripting folder) - do not edit, regenerate.
#
# API classes are renamed to PyRemote<Name> (pydavinci uses the plain names for its wrappers). Deprecated functions
# that pydavinci still calls are appended to their classes, marked "deprecated, still used by pydavinci".
from typing import Any

'''


def api_classes(source: str) -> List[str]:
    """Names of the API object classes: top level classes that are no TypedDicts."""
    tree = ast.parse(source)
    return [
        node.name
        for node in tree.body
        if isinstance(node, ast.ClassDef) and not node.bases and node.name not in NOT_RENAMED
    ]


def rename(source: str, names: List[str]) -> str:
    """Renames the class names ``names`` to ``PyRemote<name>`` in code and quoted forward references."""
    renames = {name: f"PyRemote{name}" for name in names}
    edits: Dict[int, List[Tuple[int, int, str]]] = {}
    previous = None
    for token in tokenize.generate_tokens(io.StringIO(source).readline):
        new = None
        if token.type == tokenize.NAME and token.string in renames:
            # not a method / attribute name: "def Fusion(self)", "resolve.Fusion"
            if previous is None or previous.string not in ("def", "."):
                new = renames[token.string]
        elif token.type == tokenize.STRING and token.string[1:-1] in renames and token.string[0] in "'\"":
            new = token.string[0] + renames[token.string[1:-1]] + token.string[-1]
        if new is not None:
            (row, col), (_, end_col) = token.start, token.end
            edits.setdefault(row, []).append((col, end_col, new))
        if token.type not in (tokenize.NL, tokenize.NEWLINE, tokenize.COMMENT, tokenize.INDENT, tokenize.DEDENT):
            previous = token

    lines = source.splitlines(keepends=True)
    for row, row_edits in edits.items():
        line = lines[row - 1]
        for col, end_col, new in sorted(row_edits, reverse=True):
            line = line[:col] + new + line[end_col:]
        lines[row - 1] = line
    return "".join(lines)


def expand_indentation(source: str) -> str:
    """Tabs in the indentation become 4 spaces (pydavinci style)."""
    result = []
    for line in source.splitlines(keepends=True):
        stripped = line.lstrip("\t")
        result.append("    " * (len(line) - len(stripped)) + stripped)
    return "".join(result)


def add_deprecated(source: str) -> str:
    """Appends the DEPRECATED functions to the end of their classes."""
    lines = source.splitlines(keepends=True)
    tree = ast.parse(source)
    inserts = []
    for node in tree.body:
        if isinstance(node, ast.ClassDef) and node.name in DEPRECATED:
            block = ["\n", "    # deprecated, still used by pydavinci\n"]
            block += [f"    {function}\n" for function in DEPRECATED[node.name]]
            inserts.append((node.end_lineno, block))
    for end_lineno, block in sorted(inserts, reverse=True):
        lines[end_lineno:end_lineno] = block
    return "".join(lines)


def stub_version(stub_path: Path) -> str:
    """Version of the stub: the newest version in the CHANGELOG.md next to it ("## 21.1.2"), if there is one."""
    changelog = stub_path.with_name("CHANGELOG.md")
    if changelog.is_file():
        for line in changelog.read_text(encoding="utf-8").splitlines():
            if line.startswith("## ") and line[3:4].isdigit():
                return line[3:].strip()
    return ""


def main(stub_path: Path) -> None:
    source = stub_path.read_text(encoding="utf-8")
    version = os.environ.get("RESOLVE_STUB_VERSION") or stub_version(stub_path)
    names = api_classes(source)
    generated = add_deprecated(expand_indentation(rename(source, names)))
    # drop the module docstring and the typing import of the official stub, the header has its own
    tree = ast.parse(generated)
    first = tree.body[0]
    if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant):
        generated = "".join(generated.splitlines(keepends=True)[first.end_lineno:])
    text = HEADER.format(version=version).replace("\n\n\n", "\n\n") + generated.lstrip("\n")
    ast.parse(text)  # still valid python
    TARGET.write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8"))
    print(f"Wrote {TARGET} ({len(names)} classes renamed: {', '.join(names)})")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_STUB)
